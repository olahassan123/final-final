export function getCategoryBySlug(categorySlug) {
  return serviceCatalog.find((category) => category.slug === categorySlug) || null;
}

export function getCategoryTreatments(category) {
  if (!category) return [];

  if (category.treatments?.length) {
    return category.treatments;
  }

  if (category.sections?.length) {
    return category.sections.flatMap((section) =>
      section.treatments.map((treatment) => ({
        ...treatment,
        sectionSlug: section.slug,
        sectionTitle: section.title,
      }))
    );
  }

  return [];
}

export function getTreatmentBySlugs(categorySlug, treatmentSlug) {
  const category = getCategoryBySlug(categorySlug);
  const treatment = getCategoryTreatments(category).find(
    (item) => item.slug === treatmentSlug
  );

  return {
    category,
    treatment: treatment || null,
  };
}
